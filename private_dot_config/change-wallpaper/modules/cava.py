"""
CAVA Audio Visualizer Theme Updater
"""

import re
from config import CAVA_DIR, CAVA_THEMES_DIR


def update_cava(pal):
    CAVA_DIR.mkdir(parents=True, exist_ok=True)
    CAVA_THEMES_DIR.mkdir(parents=True, exist_ok=True)

    h_colors = [
        pal.get("teal", "#00BCD4"),
        pal.get("green", "#52DF9A"),
        pal.get("yellow", "#DCC490"),
        pal.get("primary", "#D0C4FF"),
        pal.get("purple", "#DFB7FF"),
        pal.get("error", "#FD6F85"),
        pal.get("peach", "#FFB3B0"),
        pal.get("purple_bright", "#F1DAFF"),
    ]

    v_colors = [
        pal.get("teal_dark", "#004D40"),
        "#00838F",
        pal.get("teal", "#00BCD4"),
        pal.get("primary", "#D0C4FF"),
        pal.get("purple", "#DFB7FF"),
        pal.get("error", "#FD6F85"),
        pal.get("peach", "#FFB3B0"),
        "#FFD54F",
    ]

    theme_content = f"""## Dynamic Material You Theme - CAVA
## Automatically generated by change-wallpaper

[color]
horizontal_gradient = 1
horizontal_gradient_color_1 = '{h_colors[0]}'
horizontal_gradient_color_2 = '{h_colors[1]}'
horizontal_gradient_color_3 = '{h_colors[2]}'
horizontal_gradient_color_4 = '{h_colors[3]}'
horizontal_gradient_color_5 = '{h_colors[4]}'
horizontal_gradient_color_6 = '{h_colors[5]}'
horizontal_gradient_color_7 = '{h_colors[6]}'
horizontal_gradient_color_8 = '{h_colors[7]}'

gradient = 1
gradient_count = 8
gradient_color_1 = '{v_colors[0]}'
gradient_color_2 = '{v_colors[1]}'
gradient_color_3 = '{v_colors[2]}'
gradient_color_4 = '{v_colors[3]}'
gradient_color_5 = '{v_colors[4]}'
gradient_color_6 = '{v_colors[5]}'
gradient_color_7 = '{v_colors[6]}'
gradient_color_8 = '{v_colors[7]}'

blend_direction = 'up'
"""
    (CAVA_THEMES_DIR / "material-you").write_text(theme_content, encoding="utf-8")

    cava_cfg = CAVA_DIR / "config"
    if cava_cfg.is_file():
        try:
            content = cava_cfg.read_text(encoding="utf-8")
            for idx, col in enumerate(h_colors, 1):
                pattern = rf"^\s*horizontal_gradient_color_{idx}\s*=.*$"
                if re.search(pattern, content, flags=re.MULTILINE):
                    content = re.sub(pattern, f"horizontal_gradient_color_{idx} = '{col}'", content, flags=re.MULTILINE)
            for idx, col in enumerate(v_colors, 1):
                pattern = rf"^\s*gradient_color_{idx}\s*=.*$"
                if re.search(pattern, content, flags=re.MULTILINE):
                    content = re.sub(pattern, f"gradient_color_{idx} = '{col}'", content, flags=re.MULTILINE)
            cava_cfg.write_text(content, encoding="utf-8")
        except Exception as e:
            print(f"  [Note] cava config update: {e}")
